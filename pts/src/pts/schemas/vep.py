"""VEP dataset schema."""

import polars as pl

vep_schema = pl.Schema({
    'allele_string': pl.String,
    'assembly_name': pl.String,
    'intergenic_consequences': pl.List(
        pl.Struct({
            'hgvsg': pl.String,
            'consequence_terms': pl.List(pl.String),
            'impact': pl.String,
            'variant_allele': pl.String,
        })
    ),
    'colocated_variants': pl.List(
        pl.Struct({
            'allele_string': pl.String,
            'clin_sig': pl.List(pl.String),
            'clin_sig_allele': pl.String,
            'end': pl.Int64,
            'id': pl.String,
            'phenotype_or_disease': pl.Int64,
            'pubmed': pl.List(pl.Int64),
            'seq_region_name': pl.String,
            'start': pl.Int64,
            'strand': pl.Int64,
            'var_synonyms': pl.Struct({
                'ClinVar': pl.List(pl.String),
                'LMDD': pl.List(pl.String),
                'OIVD': pl.List(pl.String),
                'OMIM': pl.List(pl.Float64),
                'PharmGKB': pl.List(pl.String),
                'PhenCode': pl.List(pl.String),
                'UniProt': pl.List(pl.String),
                'dbPEX': pl.List(pl.String),
            }),
        })
    ),
    'end': pl.Int64,
    'id': pl.String,
    'input': pl.String,
    'most_severe_consequence': pl.String,
    'seq_region_name': pl.String,
    'start': pl.Int64,
    'strand': pl.Int64,
    'transcript_consequences': pl.List(
        pl.Struct({
            'conservation': pl.Float64,
            'alphamissense': pl.Struct({'am_class': pl.String, 'am_pathogenicity': pl.Float64}),
            'amino_acids': pl.String,
            'hgvsg': pl.String,
            'hgvsc': pl.String,
            'hgvsp': pl.String,
            'gene_symbol': pl.String,
            'biotype': pl.String,
            'appris': pl.String,
            'mane_select': pl.String,
            'tssdistance': pl.Int64,
            'cadd_phred': pl.Float64,
            'cadd_raw': pl.Float64,
            'canonical': pl.Int64,
            'cdna_end': pl.Int64,
            'cdna_start': pl.Int64,
            'cds_end': pl.Int64,
            'cds_start': pl.Int64,
            'codons': pl.String,
            'consequence_terms': pl.List(pl.String),
            'distance': pl.Int64,
            'flags': pl.List(pl.String),
            'gene_id': pl.String,
            'impact': pl.String,
            'lof': pl.String,
            'lof_filter': pl.String,
            'lof_flags': pl.String,
            'lof_info': pl.String,
            'polyphen_prediction': pl.String,
            'polyphen_score': pl.Float64,
            'protein_end': pl.Int64,
            'protein_start': pl.Int64,
            'sift_prediction': pl.String,
            'sift_score': pl.Float64,
            'strand': pl.Int64,
            'swissprot': pl.List(pl.String),
            'transcript_id': pl.String,
            'trembl': pl.List(pl.String),
            'uniparc': pl.List(pl.String),
            'uniprot_isoform': pl.List(pl.String),
            'variant_allele': pl.String,
        })
    ),
})
