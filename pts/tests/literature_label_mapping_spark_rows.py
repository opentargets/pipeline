def match_rows() -> list[dict]:
    """`MATCHES` as `literature_match.json` rows; `endInSentence` is `startInSentence` plus the label length."""
    return [
        {
            **CONSTANTS,
            'pmid': pmid,
            'text': text,
            'label': label,
            'type': entity_type,
            'startInSentence': start,
            'endInSentence': start + len(label or ''),
        }
        for pmid, text, label, entity_type, start in MATCHES
    ]


